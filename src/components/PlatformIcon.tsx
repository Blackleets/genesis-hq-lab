// ─── Renderer ─────────────────────────────────────────────────────────────────

export default function PlatformIcon({ platform, size = 32, className }: Props) {
  const logo = LOGOS[platform];
  if (!logo) return null;

  const pad     = logo.padding ?? 3;
  const inner   = size - pad * 2;
  const viewBox = ('viewBox' in logo && logo.viewBox) ? logo.viewBox : '0 0 24 24';

  const containerStyle: React.CSSProperties = {
    width:          size,
    height:         size,
    flexShrink:     0,
    display:        'flex',
    alignItems:     'center',
    justifyContent: 'center',
    overflow:       'hidden',
    position:       'relative',
  };

  if (logo.type === 'gradient') {
    const gradId = `ig-grad-${platform}`;
    return (
      <div className={className} style={containerStyle}>
        <svg width={size} height={size} viewBox={`0 0 ${size} ${size}`} xmlns="http://www.w3.org/2000/svg">
          <defs>
            <linearGradient id={gradId} x1="0%" y1="100%" x2="100%" y2="0%">
              {logo.colors.map((c, i) => (
                <stop key={i} offset={`${(i / (logo.colors.length - 1)) * 100}%`} stopColor={c} />
              ))}
            </linearGradient>
          </defs>
          <rect width={size} height={size} fill={`url(#${gradId})`} />
          <svg x={pad} y={pad} width={inner} height={inner} viewBox={viewBox}>
            <path d={logo.path} fill={logo.fg} />
          </svg>
        </svg>
      </div>
    );
  }

  if (logo.type === 'multi') {
    return (
      <div className={className} style={{ ...containerStyle, background: logo.bg }}>
        <svg width={inner} height={inner} viewBox={viewBox} xmlns="http://www.w3.org/2000/svg">
          {logo.children.map((child, i) => (
            <path key={i} d={child.path} fill={child.fill} />
          ))}
        </svg>
      </div>
    );
  }

  // type === 'path'
  return (
    <div className={className} style={{ ...containerStyle, background: logo.bg }}>
      <svg width={inner} height={inner} viewBox={viewBox} xmlns="http://www.w3.org/2000/svg">
        <path d={logo.path} fill={logo.fg} />
      </svg>
    </div>
  );
}
